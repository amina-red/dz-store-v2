export type MessageKey = keyof (typeof dictionary)["fr"];

/** t("onlyLeft", { n: 2 }) -> "Only 2 left" */
export function translator(locale: Locale) {
  const messages = dictionary[locale] as Record<MessageKey, string>;
  return (key: MessageKey, vars?: Record<string, string | number>): string => {
    let text = messages[key] ?? dictionary.fr[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replace(`{${name}}`, String(value));
      }
    }
    return text;
  };
}

export type T = ReturnType<typeof translator>;

export function statusKey(status: OrderStatus): MessageKey {
  return `status_${status}` as MessageKey;
}
