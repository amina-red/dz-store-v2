export function isLocale(value: unknown): value is Locale {
  return value === "ar" || value === "fr" || value === "en";
}

export function dirOf(locale: Locale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

/** The text in the buyer's language, falling back to French, then Arabic. */
export function pick(text: Translated | { ar: string; fr: string } | undefined, locale: Locale): string {
  if (!text) return "";
  const value = (text as Record<string, string>)[locale];
  return value || text.fr || text.ar || "";
}

